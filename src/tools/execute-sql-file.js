const { z } = require("zod");
const { loadDriver } = require("../db/driver");

const { getConfig } = require("../config");
const { getPool } = require("../db/pools");
const {
  applyRequestTimeout,
  attachAbort,
  writesEnabled,
  rollbackAndCheck,
  abandonedTransactionError,
} = require("../db/safety");
const {
  decodeSqlBuffer,
  splitBatches,
  previewOf,
  startsWithUse,
} = require("../sql/batches");
const { resolveSqlFile, readSqlFile } = require("../sql/files");
const {
  dbKeyShape,
  sqlFileTimeoutMsShape,
  sqlFilePath,
  MAX_LIMIT,
  MAX_BATCHES,
  MAX_BATCH_REPEAT,
  MIN_TIMEOUT_MS,
  MAX_TIMEOUT_MS,
  SQL_FILE_TIMEOUT_MS,
} = require("../validation");

const MAX_MESSAGES = 100;

/**
 * Restore the session options tedious sets on connect.
 *
 * Deployment scripts generated by SSMS start with `SET ANSI_NULLS ON` /
 * `SET QUOTED_IDENTIFIER ON`, and those survive on the connection when it goes
 * back into the pool. This is a pragmatic scrub, not a real connection reset, so
 * it only covers the options scripts actually touch.
 */
const RESTORE_SESSION_DEFAULTS = [
  "SET ANSI_NULLS ON",
  "SET ANSI_PADDING ON",
  "SET ANSI_WARNINGS ON",
  "SET ANSI_NULL_DFLT_ON ON",
  "SET ARITHABORT ON",
  "SET CONCAT_NULL_YIELDS_NULL ON",
  "SET QUOTED_IDENTIFIER ON",
  "SET NUMERIC_ROUNDABORT OFF",
].join(";\n");

const inputShape = {
  path: sqlFilePath.describe(
    "Path to a .sql file. Absolute, or relative to the project folder (the MCP server's working " +
      "directory). Must live inside the project folder or inside a folder passed to --allow-sql-dir."
  ),
  ...dbKeyShape,
  dryRun: z
    .boolean()
    .default(false)
    .describe(
      "Parse the file and report the batches without executing anything. The only mode available " +
        "when the server is read-only, and the way to audit a script before running it."
    ),
  maxRowsPerBatch: z
    .number()
    .int()
    .min(0)
    .max(MAX_LIMIT)
    .default(0)
    .describe(
      `Rows to return from each batch's first recordset (0..${MAX_LIMIT}). Default 0: only row counts, ` +
        "which is what a deployment script needs."
    ),
  ...sqlFileTimeoutMsShape,
};

const batchShape = z.object({
  index: z.number().int().nonnegative(),
  startLine: z.number().int().positive(),
  endLine: z.number().int().positive(),
  lineCount: z.number().int().positive(),
  repeat: z.number().int().nonnegative(),
  preview: z.string(),
  skipped: z.boolean().optional(),
  rowsAffected: z.array(z.number().int().nonnegative()).optional(),
  recordsetCount: z.number().int().nonnegative().optional(),
  rowCounts: z.array(z.number().int().nonnegative()).optional(),
  rows: z.array(z.record(z.unknown())).optional(),
});

const outputShape = {
  db: z.string(),
  dbKey: z.string(),
  file: z.string(),
  sizeBytes: z.number().int().nonnegative(),
  sha256: z.string(),
  encoding: z.string(),
  dryRun: z.boolean(),
  committed: z.boolean(),
  batchCount: z.number().int().nonnegative(),
  batches: z.array(batchShape),
  messages: z.array(z.string()),
  message: z.string(),
};

function describeBatch(batch) {
  return {
    index: batch.index,
    startLine: batch.startLine,
    endLine: batch.endLine,
    lineCount: batch.lineCount,
    repeat: batch.repeat,
    preview: previewOf(batch.sql),
  };
}

function summarizeBatch(batch, result, maxRows) {
  const out = describeBatch(batch);
  if (!result) {
    out.skipped = true;
    return out;
  }
  out.rowsAffected = (result.rowsAffected || []).map(Number);
  const recordsets = result.recordsets || [];
  out.recordsetCount = recordsets.length;
  out.rowCounts = recordsets.map((rs) => rs.length);
  if (maxRows > 0 && recordsets.length > 0) {
    out.rows = recordsets[0].slice(0, maxRows);
  }
  return out;
}

/**
 * Turn a SQL Server error into one that points at a line of the FILE.
 *
 * tedious reports `lineNumber` relative to the batch it sent, which is useless on
 * its own once the file has been split on GO. Adding the batch's start line back
 * is what turns "Incorrect syntax near ')'" into something the user can jump to.
 */
function toFileError(err, batch, file, run) {
  const parts = [];
  const runLabel = batch.repeat > 1 ? `, run ${run + 1}/${batch.repeat}` : "";
  parts.push(
    `Batch #${batch.index} failed (file lines ${batch.startLine}-${batch.endLine}${runLabel}).`
  );
  if (Number.isInteger(err.lineNumber) && err.lineNumber > 0) {
    parts.push(`Error at ${file}:${batch.startLine + err.lineNumber - 1}.`);
  }
  const codes = [];
  if (err.number !== undefined) codes.push(`number ${err.number}`);
  if (err.state !== undefined) codes.push(`state ${err.state}`);
  if (err.class !== undefined) codes.push(`severity ${err.class}`);
  if (codes.length > 0) parts.push(`SQL error ${codes.join(", ")}.`);
  if (err.procName) parts.push(`In ${err.procName}.`);
  parts.push(err.message);
  if (Array.isArray(err.precedingErrors) && err.precedingErrors.length > 0) {
    parts.push(`(${err.precedingErrors.length} preceding error(s) suppressed.)`);
  }
  // Deliberately silent about the rollback: whether it happened is only known once the
  // cleanup has run, and the caller appends the verdict then (see `rolledBackError`).
  const wrapped = new Error(parts.join(" "));
  wrapped.cause = err;
  return wrapped;
}

/**
 * The failure the caller sees once the transaction is KNOWN to be gone.
 *
 * Stated after the cleanup, not before it. The old message claimed "which was rolled
 * back - nothing was applied" unconditionally, and that was a guess: a batch timeout or
 * a client cancel leaves the request in flight, tedious serialises requests per
 * connection, so the ROLLBACK could not even be sent and the claim was false. Now the
 * sentence is only added on the path where the rollback (ours or the server's) has
 * actually completed; the other path raises `abandonedTransactionError` instead.
 */
function rolledBackError(err) {
  err.message +=
    " The whole script runs in a single transaction, which was rolled back - nothing was applied.";
  return err;
}

function respond(structured) {
  return {
    content: [{ type: "text", text: JSON.stringify(structured, null, 2) }],
    structuredContent: structured,
  };
}

async function handler(
  {
    path: filePath,
    dbKey,
    dryRun = false,
    maxRowsPerBatch = 0,
    timeoutMs = SQL_FILE_TIMEOUT_MS,
  },
  extra
) {
  const sqlLib = loadDriver();
  // Checked first, before any filesystem or pool access, so a read-only server
  // never even opens the file for a non-dry run.
  if (!dryRun && !writesEnabled(process.env, dbKey)) {
    throw new Error(
      dbKey
        ? `execute_sql_file needs writes enabled for '${dbKey}'. Restart the server with ` +
          `--allow-writes-for ${dbKey} (MSSQL_${String(dbKey).toUpperCase()}_ENABLE_WRITES=true), or ` +
          "--allow-writes for every database, or call again with dryRun:true to inspect the script " +
          "without executing it."
        : "execute_sql_file needs writes enabled. Restart the server with --allow-writes " +
          "(MSSQL_ENABLE_WRITES=true), or call again with dryRun:true to inspect the script " +
          "without executing it."
    );
  }

  const { realPath, sizeBytes } = resolveSqlFile(filePath);
  const buffer = readSqlFile(realPath);
  const { text, encoding } = decodeSqlBuffer(buffer);
  const batches = splitBatches(text);

  if (batches.length === 0) {
    throw new Error(`No executable SQL found in ${realPath}.`);
  }
  if (batches.length > MAX_BATCHES) {
    throw new Error(
      `${realPath} splits into ${batches.length} batches (max ${MAX_BATCHES}). Split the script.`
    );
  }
  for (const batch of batches) {
    if (batch.repeat > MAX_BATCH_REPEAT) {
      throw new Error(
        `'GO ${batch.repeat}' after line ${batch.endLine} exceeds the maximum repeat count of ${MAX_BATCH_REPEAT}.`
      );
    }
    if (startsWithUse(batch.sql)) {
      throw new Error(
        `Batch #${batch.index} (line ${batch.startLine}) starts with USE. That would change the ` +
          "database of a pooled connection and leak into later calls - remove it and select the " +
          "database with `dbKey` instead."
      );
    }
  }

  const sha256 = crypto.createHash("sha256").update(buffer).digest("hex");
  const { dbKey: actualKey, config } = getConfig(dbKey);
  const base = {
    db: config.database,
    dbKey: actualKey,
    file: realPath,
    sizeBytes,
    sha256,
    encoding,
    batchCount: batches.length,
  };

  if (dryRun) {
    return respond({
      ...base,
      dryRun: true,
      committed: false,
      batches: batches.map(describeBatch),
      messages: [],
      message: `Dry run: ${batches.length} batch(es) parsed from ${encoding} source. Nothing was executed.`,
    });
  }

  const signal = extra?.signal;
  if (signal?.aborted) throw new Error("Request aborted");
  const pool = await getPool(actualKey, config);

  // All batches share ONE transaction, and that is not only about atomicity: a
  // Request built on the pool acquires and releases a connection per .batch(),
  // so the batches would land on different connections and GO semantics would
  // break - `SET ANSI_NULLS ON` would not apply to the following CREATE
  // PROCEDURE, and a #temp table from batch 1 would not exist in batch 2.
  // A Transaction pins one connection for the whole script.
  const transaction = new sqlLib.Transaction(pool);
  let serverRolledBack = false;
  transaction.on("rollback", () => {
    serverRolledBack = true;
  });
  await transaction.begin(sqlLib.ISOLATION_LEVEL.READ_COMMITTED);

  const messages = [];
  const results = [];
  // Whether a cancel was fired at the request that failed. The cleanup needs it: a
  // cancelled request is still in flight until the server acknowledges the ATTENTION,
  // and the ROLLBACK has to wait for that before it can even be sent.
  let aborted = false;
  let failure = null;
  try {
    for (const batch of batches) {
      let last = null;
      for (let run = 0; run < batch.repeat; run++) {
        if (signal?.aborted) throw new Error("Request aborted");
        // El timeout va estampado en la peticion de tedious, no en el pool: el
        // `requestTimeout` del pool es de 30 s y lo comparten todas las tools, y
        // subirselo a todas para que quepa un despliegue tambien le quitaria el freno
        // a un SELECT desbocado. Ver applyRequestTimeout en db/safety.js.
        const request = applyRequestTimeout(
          new sqlLib.Request(transaction),
          timeoutMs
        );
        const abort = attachAbort(request, signal);
        request.on("info", (info) => {
          if (messages.length < MAX_MESSAGES) {
            messages.push(String(info?.message ?? info));
          }
        });
        try {
          last = await request.batch(batch.sql);
        } catch (err) {
          aborted = abort.aborted;
          throw toFileError(err, batch, realPath, run);
        } finally {
          abort.detach();
        }
      }
      results.push(summarizeBatch(batch, last, maxRowsPerBatch));
    }

    await applyRequestTimeout(
      new sqlLib.Request(transaction),
      timeoutMs
    ).batch(RESTORE_SESSION_DEFAULTS);
    await transaction.commit();
  } catch (err) {
    failure = err;
  }

  if (failure) {
    // The same wait-then-rollback-then-check as every read and write, instead of the
    // old `rollback()` inside an empty catch. That catch was exactly the bug the pool
    // hygiene fixed elsewhere: the request was still in flight after a batch timeout or
    // a client cancel, the ROLLBACK failed with EREQINPROG, and the connection went back
    // to the pool with the deployment's transaction - and its schema locks, which DO
    // block other sessions - still open. Now that connection is either proven clean or
    // destroyed, and the caller is told which.
    const cleanup = serverRolledBack
      ? { ok: true, serverRolledBack: true }
      : await rollbackAndCheck(pool, transaction, { aborted, mssql: sqlLib });
    if (!cleanup.ok) throw abandonedTransactionError(cleanup, failure);
    throw rolledBackError(failure);
  }

  const executed = results.filter((r) => !r.skipped).length;
  return respond({
    ...base,
    dryRun: false,
    committed: true,
    batches: results,
    messages,
    message: `Executed ${executed} of ${batches.length} batch(es) and committed.`,
  });
}

